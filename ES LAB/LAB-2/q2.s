	AREA RESET, DATA, READONLY
	EXPORT __Vectors
__Vectors
	DCD 0x10001000
	DCD Reset_Handler
	ALIGN
	AREA mycode, CODE, READONLY
	ENTRY
	EXPORT Reset_Handler
Reset_Handler
	MOV R2,#N
	LDR R0,=SRC+(N-1)*4
	LDR R1,=SRC+(N-1+S)*4
CONT
	LDR R3,[R0],#-4
	STR R3,[R1],#-4
	SUBS R2,#1
	BNE CONT
STOP
	B STOP  
N EQU 10
S EQU 2	
    AREA DATASEG, DATA, READWRITE
SRC DCD 10,11,12,13,14,15,70,80,90,100,0,0
	END