def print_ord():
    print(ord('a')) #-- 97
    print(ord('A')) #-- 65
    print(ord('0')) #-- 48
    print(ord('1')) #-- 49
    print(ord('9')) #-- 57
print_ord()

'''
Char       | Unicode/ASCII Value 
-----------------------------------
'a'        | 97                  
'A'        | 65                  
'0'        | 48                  
'1'        | 49                  
'9'        | 57                
'''